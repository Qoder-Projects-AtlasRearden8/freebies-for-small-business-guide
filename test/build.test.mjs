test('build is deterministic', () => {
  const secondRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'freebie-guide-second-'));
  try {
    buildSite({ outDir: secondRoot });
    const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
    const relative = (dir) =>
      walk(dir)
        .map((file) => path.relative(dir, file))
        .sort();

    const firstFiles = relative(outDir);
    const secondFiles = relative(secondRoot);
    assert.deepEqual(secondFiles, firstFiles, 'build output file lists differ');

    for (const file of firstFiles) {
      assert.equal(
        hash(path.join(outDir, file)),
        hash(path.join(secondRoot, file)),
        `build is not deterministic for ${file}`
      );
    }
  } finally {
    fs.rmSync(secondRoot, { recursive: true, force: true });
  }
});

test('local server serves pages, assets, 404s, and blocks traversal', async () => {
  const child = spawn(process.execPath, [SERVE], {
    env: { ...process.env, PORT: '0', HOST: '127.0.0.1', SERVE_DIR: outDir },
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  let stderr = '';
  child.stderr.on('data', (chunk) => {
    stderr += chunk.toString();
  });

  const stop = async () => {
    if (!child.killed) child.kill('SIGTERM');
    await Promise.race([
      once(child, 'exit'),
      new Promise((resolve) => setTimeout(resolve, 2000)),
    ]);
  };

  try {
    const base = await new Promise((resolve, reject) => {
      let buffer = '';
      const timer = setTimeout(() => reject(new Error(`server did not start: ${stderr}`)), 5000);
      child.stdout.on('data', (chunk) => {
        buffer += chunk.toString();
        const match = buffer.match(/http:\/\/127\.0\.0\.1:(\d+)/);
        if (match) {
          clearTimeout(timer);
          resolve(match[0]);
        }
      });
      child.on('error', (error) => {
        clearTimeout(timer);
        reject(error);
      });
      child.on('exit', (code) => {
        clearTimeout(timer);
        reject(new Error(`server exited early with ${code}: ${stderr}`));
      });
    });

    const home = await fetch(`${base}/`, { signal: AbortSignal.timeout(5000) });
    assert.equal(home.status, 200);
    assert.match(home.headers.get('content-type') || '', /text\/html/);
    assert.match(await home.text(), /Free Tools to Run a Small Business/);

    const chapter = await fetch(`${base}/01-accounting.html`, { signal: AbortSignal.timeout(5000) });
    assert.equal(chapter.status, 200);

    const css = await fetch(`${base}/assets/style.css`, { signal: AbortSignal.timeout(5000) });
    assert.equal(css.status, 200);
    assert.match(css.headers.get('content-type') || '', /text\/css/);
    assert.match(css.headers.get('x-content-type-options') || '', /nosniff/);

    const missing = await fetch(`${base}/not-a-page.html`, { signal: AbortSignal.timeout(5000) });
    assert.equal(missing.status, 404);

    const port = Number(new URL(base).port);
    const traversal = await new Promise((resolve, reject) => {
      const request = http.get(
        {
          host: '127.0.0.1',
          port,
          path: '/%2e%2e/%2e%2e/etc/passwd',
        },
        (response) => {
          response.resume();
          resolve(response.statusCode);
        }
      );
      request.on('error', reject);
    });
    assert.ok([403, 404].includes(traversal), `path traversal should not succeed, got ${traversal}`);
  } finally {
    await stop();
  }
});
