test('every page has required structure, metadata, and accessible landmarks', () => {
  const titles = new Set();

  for (const [file, html] of pages) {
    assert.match(html, /^<!doctype html>/i, `${file} should start with a doctype`);
    assert.match(html, /Generated by scripts\/build\.mjs/, `${file} should be generated`);
    assert.match(html, /<html lang="en"/, `${file} should declare English`);
    assert.match(html, /<meta charset="utf-8">/, `${file} should declare a charset`);
    assert.match(html, /<meta name="viewport"/, `${file} should be responsive`);
    assert.match(html, /<meta name="description" content="[^"]+"/, `${file} needs a description`);
    assert.match(html, /<meta name="referrer" content="no-referrer">/, `${file} needs referrer policy`);
    assert.match(html, /<a class="skip-link" href="#main">Skip to content<\/a>/, `${file} needs a skip link`);

    const title = html.match(/<title>([^<]+)<\/title>/);
    assert.ok(title, `${file} needs a title`);
    assert.ok(title[1].trim().length > 3, `${file} title is too short`);
    assert.ok(!titles.has(title[1]), `duplicate page title: ${title[1]}`);
    titles.add(title[1]);

    assert.equal((html.match(/<h1[\s>]/g) || []).length, 1, `${file} needs exactly one h1`);
    assert.match(html, /<main id="main"/, `${file} needs a main landmark`);
    assert.match(html, /Copyright \(c\) 2026 Asdale Dynamics, LLC/, `${file} needs the 2026 copyright line`);
    assert.match(html, /<dialog class="search-dialog" id="search-dialog" aria-labelledby="search-title"/, `${file} needs an accessible search dialog`);
    assert.match(html, /<label class="visually-hidden" for="search-input">/, `${file} needs a search label`);
    assert.match(html, /id="search-status" role="status" aria-live="polite"/, `${file} needs a live search status`);
    assert.match(html, /href="#main">Skip to content/, `${file} skip link should target main`);

    assert.doesNotMatch(html, /<script(?![^>]*\bsrc=)[^>]*>/i, `${file} should not use inline scripts`);
    assert.doesNotMatch(html, /\son[a-z]+\s*=/i, `${file} should not use inline event handlers`);
    assert.doesNotMatch(html, /href="javascript:/i, `${file} should not use javascript: URLs`);

    const ids = pageIds(html);
    assert.equal(ids.size, [...html.matchAll(/\sid="([^"]+)"/g)].length, `${file} has duplicate ids`);
    assertBalanced(html, file);
  }
});

test('all internal links and fragments resolve', () => {
  const attrRe = /(?:href|src)="([^"]+)"/g;

  for (const [file, html] of pages) {
    const ids = pageIds(html);
    for (const match of html.matchAll(attrRe)) {
      const value = match[1];
      if (/^(?:https?:|mailto:|tel:|data:|\/\/)/i.test(value)) continue;

      if (value.startsWith('#')) {
        assert.ok(ids.has(value.slice(1)), `${file} links to missing fragment ${value}`);
        continue;
      }

      const [rawPath, fragment] = value.split('#');
      if (!rawPath) continue;
      const target = path.resolve(outDir, rawPath);
      assert.ok(target.startsWith(`${outDir}${path.sep}`), `${file} links outside the site: ${value}`);
      assert.ok(fs.existsSync(target), `${file} links to missing file ${value}`);
      assert.ok(fs.statSync(target).isFile(), `${file} links to a non-file ${value}`);

      if (fragment) {
        const targetHtml = fs.readFileSync(target, 'utf8');
        assert.ok(pageIds(targetHtml).has(fragment), `${file} links to missing fragment ${value}`);
      }
    }

    assert.doesNotMatch(html, /href="[^"]*\.md(?:#|")/, `${file} still contains a Markdown link`);
  }
});

test('site is local-first and loads no third-party assets', () => {
  const assetTagRe = /<(script|link|img|source|iframe|video|audio)\b([^>]*)>/gi;

  for (const [file, html] of pages) {
    for (const match of html.matchAll(assetTagRe)) {
      const attrs = match[2];
      const url = attrs.match(/\b(?:src|href)="([^"]+)"/i);
      if (!url) continue;
      assert.doesNotMatch(
        url[1],
        /^(?:https?:)?\/\//i,
        `${file} loads a third-party asset: ${url[1]}`
      );
    }
    assert.doesNotMatch(html, /googletagmanager|gtag\(|plausible\.io|matomo|connect\.facebook\.net/i);
  }

  const css = fs.readFileSync(path.join(outDir, 'assets', 'style.css'), 'utf8');
  assert.doesNotMatch(css, /@import\b/i, 'CSS should not import external styles');
  assert.doesNotMatch(css, /url\(\s*['"]?https?:/i, 'CSS should not load remote URLs');
  assert.match(css, /prefers-color-scheme:\s*dark/, 'CSS should support dark mode');
  assert.match(css, /@media print/, 'CSS should include print styles');
  assert.match(css, /prefers-reduced-motion/, 'CSS should respect reduced motion');

  const app = fs.readFileSync(path.join(outDir, 'assets', 'app.js'), 'utf8');
  assert.doesNotMatch(app, /\bfetch\s*\(|XMLHttpRequest|WebSocket/i, 'Client JS should not make network requests');
  assert.match(app, /GUIDE_SEARCH/, 'Client search should use the local index');
});

