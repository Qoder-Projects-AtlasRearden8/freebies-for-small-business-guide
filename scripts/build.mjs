function toc(headings) {
  if (!headings.length) return '';
  const items = headings
    .map(
      (heading) =>
        `<li class="lvl-${heading.level}"><a href="#${escapeAttr(heading.id)}">${escapeHtml(
          heading.text
        )}</a></li>`
    )
    .join('\n          ');
  return `<details class="page-toc">
      <summary>On this page</summary>
      <nav aria-label="On this page">
        <ul class="toc-list">
          ${items}
        </ul>
      </nav>
    </details>`;
}

function pager(prev, next) {
  if (!prev && !next) return '';
  const cards = [];
  if (prev) {
    cards.push(`<a class="pager-card prev" href="${prev.href}">
        <span class="pager-label">Previous</span>
        <span class="pager-title">${escapeHtml(prev.title)}</span>
      </a>`);
  }
  if (next) {
    cards.push(`<a class="pager-card next" href="${next.href}">
        <span class="pager-label">Next</span>
        <span class="pager-title">${escapeHtml(next.title)}</span>
      </a>`);
  }
  return `<nav class="pager${cards.length === 1 ? ' single' : ''}" aria-label="Chapter navigation">
      ${cards.join('\n      ')}
    </nav>`;
}

