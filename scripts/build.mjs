function buildSearchIndex(pages) {
  const entries = pages.map((page) => ({
    slug: `${page.slug}.html`,
    number: page.number || '',
    short: page.short || 'Overview',
    title: page.title,
    group: page.group || 'Overview',
    headings: page.headings.map((heading) => ({ id: heading.id, text: heading.text })),
    text: page.plainText.slice(0, 12000),
  }));
  return `window.GUIDE_SEARCH = ${JSON.stringify({
    checked: CHECKED,
    entries,
  }).replace(/</g, '\\u003c')};\n`;
}

export function buildSite(options = {}) {
  const root = options.root || DEFAULT_ROOT;
  const docsDir = options.docsDir || path.join(root, 'docs');
  const outDir = options.outDir || path.join(root, 'site');
  const assetsSrc = options.assetsSrc || path.join(root, 'site', 'src', 'assets');
  const licensePath = options.licensePath || path.join(root, 'LICENSE');

  if (!fs.existsSync(docsDir)) {
    throw new Error(`Docs directory not found: ${docsDir}`);
  }
  if (!fs.existsSync(assetsSrc)) {
    throw new Error(`Site source assets not found: ${assetsSrc}`);
  }
  if (!fs.existsSync(licensePath)) {
    throw new Error(`License file not found: ${licensePath}`);
  }

  const { docs, linkMap } = loadDocs(docsDir);
  const chapters = [];
  let overviewDoc = null;

  docs.forEach((doc) => {
    if (doc.slug === 'README') {
      overviewDoc = doc;
      return;
    }
    const meta = CHAPTER_META[doc.slug];
    if (!meta) return;
    const parsed = parseMarkdown(doc.markdown, { linkMap });
    chapters.push({
      ...meta,
      slug: doc.slug,
      title: parsed.title || meta.short,
      bodyHtml: parsed.bodyHtml,
      printBodyHtml: parseMarkdown(doc.markdown, {
        linkMap,
        idPrefix: `print-${doc.slug}-`,
      }).bodyHtml,
      headings: parsed.headings,
      plainText: parsed.plainText,
      words: parsed.words,
      readingTime: parsed.readingTime,
    });
  });

  chapters.sort((a, b) => a.number.localeCompare(b.number));

  if (!overviewDoc) throw new Error('docs/README.md not found');
  if (chapters.length !== Object.keys(CHAPTER_META).length) {
    throw new Error(
      `Expected ${Object.keys(CHAPTER_META).length} chapters, found ${chapters.length}`
    );
  }

  const overviewParsed = parseMarkdown(overviewDoc.markdown, { linkMap });
  const overview = {
    slug: 'overview',
    title: overviewParsed.title || SITE.title,
    bodyHtml: overviewParsed.bodyHtml,
    headings: overviewParsed.headings,
    plainText: overviewParsed.plainText,
    words: overviewParsed.words,
    readingTime: overviewParsed.readingTime,
  };

  const totalWords = chapters.reduce((sum, chapter) => sum + chapter.words, 0);
  const stats = {
    chapters: chapters.length,
    words: totalWords,
    minutes: Math.ceil(totalWords / 220),
  };

  fs.mkdirSync(outDir, { recursive: true });
  fs.mkdirSync(path.join(outDir, 'assets'), { recursive: true });
  fs.cpSync(assetsSrc, path.join(outDir, 'assets'), { recursive: true });

  const licenseText = fs.readFileSync(licensePath, 'utf8');
  const pages = new Map();
  pages.set('index.html', renderLandingPage(chapters, stats));
  pages.set('overview.html', renderOverviewPage(overview, chapters));
  chapters.forEach((chapter) => {
    pages.set(`${chapter.slug}.html`, renderChapterPage(chapter, chapters));
  });
  pages.set('print.html', renderPrintPage(chapters, licenseText));
  pages.set('license.html', renderLicensePage(licenseText, chapters));

  fs.writeFileSync(
    path.join(outDir, 'assets', 'search-index.js'),
    buildSearchIndex([{ ...overview, number: '', short: 'Overview', group: 'Overview' }, ...chapters]),
    'utf8'
  );

  for (const [file, html] of pages) {
    fs.writeFileSync(path.join(outDir, file), html, 'utf8');
  }

  for (const file of fs.readdirSync(outDir)) {
    if (!file.endsWith('.html') || pages.has(file)) continue;
    const full = path.join(outDir, file);
    const head = fs.readFileSync(full, 'utf8').slice(0, 400);
    if (head.includes(GENERATED_MARKER)) fs.unlinkSync(full);
  }

  return {
    outDir,
    pages: [
      { slug: 'overview', title: overview.title, number: '', short: 'Overview', group: 'Overview', ...overview },
      ...chapters,
    ],
    chapterCount: chapters.length,
    totalWords,
    stats,
    checked: CHECKED,
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const result = buildSite();
  console.log(
    `Built ${result.chapterCount} chapters + landing, overview, print, and license pages ` +
      `(${result.stats.words.toLocaleString('en-US')} words) in ${result.outDir}`
  );
}
