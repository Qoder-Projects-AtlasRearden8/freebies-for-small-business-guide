function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function escapeAttr(value) {
  return escapeHtml(value).replace(/'/g, '&#39;');
}

function slugify(value) {
  return String(value)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/&[a-z]+;/gi, ' ')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 72) || 'section';
}

function stripInline(value) {
  return String(value)
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/<([^>]+)>/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .trim();
}

function plainText(markdown) {
  return markdown
    .replace(/```[\w-]*\n([\s\S]*?)```/g, ' $1 ')
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/^\s*>\s?/gm, '')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/<((?:https?:\/\/)[^>]+)>/g, ' $1 ')
    .replace(/[`*_|#]/g, ' ')
    .replace(/^\s*[-+]\s+/gm, '')
    .replace(/^\s*\d+[.)]\s+/gm, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function sanitizeUrl(url) {
  const value = String(url).trim();
  if (!value) return null;
  if (/^(?:javascript|data|vbscript):/i.test(value)) return null;
  return value;
}

function rewriteHref(href, linkMap) {
  const raw = String(href).trim();
  if (!raw || /^(?:https?:|mailto:|#)/i.test(raw)) return raw;
  const [target, hash = ''] = raw.split('#');
  const suffix = hash ? `#${hash}` : '';
  if (target === '../LICENSE' || target === 'LICENSE') return `license.html${suffix}`;
  if (linkMap[target]) return `${linkMap[target]}${suffix}`;
  const base = target.split('/').pop();
  if (linkMap[base]) return `${linkMap[base]}${suffix}`;
  return raw;
}

function renderInline(text, linkMap) {
  if (!text) return '';
  const codeStore = [];
  let out = escapeHtml(text);

  out = out.replace(/`([^`]+)`/g, (_match, code) => {
    const token = `\u0000C${codeStore.length}\u0000`;
    codeStore.push(`<code>${code}</code>`);
    return token;
  });

  out = out.replace(/&lt;(https?:\/\/[^\s<>]+)&gt;/g, (_match, url) => {
    const clean = url.replace(/&amp;/g, '&');
    const safe = sanitizeUrl(clean);
    if (!safe) return escapeHtml(url);
    return `<a href="${escapeAttr(safe)}">${escapeHtml(clean)}</a>`;
  });

  out = out.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (match, label, url) => {
    const clean = url.replace(/&amp;/g, '&');
    const safe = sanitizeUrl(rewriteHref(clean, linkMap));
    if (!safe) return match;
    return `<a href="${escapeAttr(safe)}">${label}</a>`;
  });

  out = out.replace(/\*\*([^*\n]+)\*\*/g, '<strong>$1</strong>');
  out = out.replace(/(^|[\s(])\*([^*\n]+)\*(?=[\s.,;:!?)]|$)/g, '$1<em>$2</em>');

  out = out.replace(/\u0000C(\d+)\u0000/g, (_match, index) => codeStore[Number(index)]);
  return out;
}

function splitRow(line) {
  let value = line.trim();
  if (value.startsWith('|')) value = value.slice(1);
  if (value.endsWith('|')) value = value.slice(0, -1);
  return value.split('|').map((cell) => cell.trim());
}

function isTableSep(line) {
  if (!line || !line.includes('|')) return false;
  const cells = splitRow(line);
  return cells.length > 0 && cells.every((cell) => /^:?-{3,}:?$/.test(cell));
}

function isTableStart(lines, index) {
  return (
    index + 1 < lines.length &&
    lines[index].includes('|') &&
    isTableSep(lines[index + 1])
  );
}

function alignClass(cell) {
  const left = cell.startsWith(':');
  const right = cell.endsWith(':');
  if (left && right) return 'align-center';
  if (right) return 'align-right';
  return '';
}

function parseMarkdown(markdown, options = {}) {
  const linkMap = options.linkMap || {};
  const idPrefix = options.idPrefix || '';
  const lines = String(markdown).replace(/\r\n?/g, '\n').split('\n');
  const headings = [];
  const usedIds = new Set();
  let title = '';
  let body = '';
  let i = 0;

  const inline = (text) => renderInline(text, linkMap);

  function uniqueId(text) {
    const base = `${idPrefix}${slugify(text)}`;
    let id = base;
    let n = 2;
    while (usedIds.has(id)) {
      id = `${base}-${n}`;
      n += 1;
    }
    usedIds.add(id);
    return id;
  }

  function matchList(line) {
    const unordered = line.match(/^(\s*)[-*+]\s+(.*)$/);
    if (unordered) {
      return { indent: unordered[1].length, ordered: false, text: unordered[2] };
    }
    const ordered = line.match(/^(\s*)(\d+)[.)]\s+(.*)$/);
    if (ordered) {
      return { indent: ordered[1].length, ordered: true, text: ordered[3] };
    }
    return null;
  }

  function parseList(start, baseIndent, ordered) {
    let html = ordered ? '<ol>' : '<ul>';
    let index = start;
    let openItem = false;

    while (index < lines.length) {
      const line = lines[index];
      if (/^\s*$/.test(line)) {
        let look = index + 1;
        while (look < lines.length && /^\s*$/.test(lines[look])) look += 1;
        const next = look < lines.length ? matchList(lines[look]) : null;
        if (next && next.indent >= baseIndent && next.ordered === ordered) {
          index = look;
          continue;
        }
        break;
      }

      const item = matchList(line);
      if (item && item.indent === baseIndent && item.ordered === ordered) {
        if (openItem) html += '</li>';
        html += `<li>${inline(item.text)}`;
        openItem = true;
        index += 1;
        continue;
      }

      if (item && item.indent > baseIndent) {
        const [nested, nextIndex] = parseList(index, item.indent, item.ordered);
        html += nested;
        index = nextIndex;
        continue;
      }

      if (openItem && /^\s{2,}\S/.test(line)) {
        html += ` ${inline(line.trim())}`;
        index += 1;
        continue;
      }

      break;
    }

    if (openItem) html += '</li>';
    html += ordered ? '</ol>\n' : '</ul>\n';
    return [html, index];
  }

  while (i < lines.length) {
    const line = lines[i];

    if (/^\s*$/.test(line)) {
      i += 1;
      continue;
    }

    const fence = line.match(/^```([\w-]*)\s*$/);
    if (fence) {
      const codeLines = [];
      i += 1;
      while (i < lines.length && !/^```\s*$/.test(lines[i])) {
        codeLines.push(lines[i]);
        i += 1;
      }
      i += 1;
      const language = fence[1] || 'text';
      body += `<pre><code class="language-${escapeAttr(language)}">${escapeHtml(codeLines.join('\n'))}</code></pre>\n`;
      continue;
    }

    const heading = line.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (heading) {
      const level = heading[1].length;
      const text = stripInline(heading[2]);
      if (level === 1 && !title) {
        title = text;
      } else {
        const renderedLevel = Math.min(level, 4);
        const id = uniqueId(text);
        headings.push({ level: renderedLevel, text, id });
        body += `<h${renderedLevel} id="${escapeAttr(id)}">${inline(heading[2])}</h${renderedLevel}>\n`;
      }
      i += 1;
      continue;
    }

    if (/^\s*(?:---+|\*\*\*+|___+)\s*$/.test(line)) {
      body += '<hr>\n';
      i += 1;
      continue;
    }

    if (/^\s*>/.test(line)) {
      const quoteLines = [];
      while (i < lines.length && /^\s*>/.test(lines[i])) {
        quoteLines.push(lines[i].replace(/^\s*>\s?/, ''));
        i += 1;
      }
      const paragraphs = quoteLines
        .join('\n')
        .split(/\n\s*\n/)
        .map((part) => part.split('\n').join(' ').trim())
        .filter(Boolean);
      body += `<blockquote class="callout">${paragraphs
        .map((part) => `<p>${inline(part)}</p>`)
        .join('')}</blockquote>\n`;
      continue;
    }

    if (isTableStart(lines, i)) {
      const headers = splitRow(lines[i]);
      const separators = splitRow(lines[i + 1]);
      const aligns = headers.map((_header, index) => alignClass(separators[index] || ''));
      i += 2;
      const rows = [];
      while (i < lines.length && lines[i].includes('|') && !/^\s*$/.test(lines[i])) {
        rows.push(splitRow(lines[i]));
        i += 1;
      }
      body += '<div class="table-wrap"><table><thead><tr>';
      headers.forEach((header, index) => {
        const cls = aligns[index] ? ` class="${aligns[index]}"` : '';
        body += `<th scope="col"${cls}>${inline(header)}</th>`;
      });
      body += '</tr></thead><tbody>';
      rows.forEach((row) => {
        body += '<tr>';
        headers.forEach((_header, index) => {
          const cls = aligns[index] ? ` class="${aligns[index]}"` : '';
          body += `<td${cls}>${inline(row[index] || '')}</td>`;
        });
        body += '</tr>';
      });
      body += '</tbody></table></div>\n';
      continue;
    }

    const item = matchList(line);
    if (item) {
      const [listHtml, nextIndex] = parseList(i, item.indent, item.ordered);
      body += listHtml;
      i = nextIndex;
      continue;
    }

    const paragraph = [line.trim()];
    i += 1;
    while (
      i < lines.length &&
      !/^\s*$/.test(lines[i]) &&
      !/^```/.test(lines[i]) &&
      !/^#{1,6}\s/.test(lines[i]) &&
      !/^\s*>/.test(lines[i]) &&
      !/^\s*(?:---+|\*\*\*+|___+)\s*$/.test(lines[i]) &&
      !matchList(lines[i]) &&
      !isTableStart(lines, i)
    ) {
      paragraph.push(lines[i].trim());
      i += 1;
    }
    body += `<p>${inline(paragraph.join(' '))}</p>\n`;
  }

  const text = plainText(markdown);
  const words = text ? text.split(/\s+/).filter(Boolean).length : 0;

  return {
    title,
    bodyHtml: body.trim(),
    headings: headings.filter((h) => h.level === 2 || h.level === 3),
    allHeadings: headings,
    plainText: text,
    words,
    readingTime: Math.max(1, Math.ceil(words / 220)),
  };
}

function loadDocs(docsDir) {
  const files = fs
    .readdirSync(docsDir)
    .filter((file) => file.endsWith('.md'))
    .sort();
  const docs = files.map((file) => ({
    file,
    slug: file.replace(/\.md$/, ''),
    markdown: fs.readFileSync(path.join(docsDir, file), 'utf8'),
  }));

  const linkMap = {
    'README.md': 'overview.html',
    README: 'overview.html',
    LICENSE: 'license.html',
    '../LICENSE': 'license.html',
  };
  docs.forEach((doc) => {
    linkMap[doc.file] = `${doc.slug}.html`;
    if (doc.slug !== 'README') linkMap[doc.slug] = `${doc.slug}.html`;
  });

  return { docs, linkMap };
}

